#!/usr/bin/env python3
"""Build docs/FEATURE_MAP.md from the per-area fragments in docs/featuremap/*.md.

Each fragment is a markdown table body (no header): one row per ShareX feature,
``| feature | module | mechanism | status | test |``. Status is ``done``, ``planned``, or
``excluded: <evidence URL>``.

    python3 scripts/featuremap.py build    # regenerate FEATURE_MAP.md (and print the counts)
    python3 scripts/featuremap.py check    # exit 1 if any row is not done/excluded
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FRAG = ROOT / "docs" / "featuremap"
OUT = ROOT / "docs" / "FEATURE_MAP.md"

ORDER = ["mechanisms", "hotkeys", "after_capture", "after_upload", "task_settings", "nameparser", "shapes",
         "editor", "effects", "uploaders_image", "uploaders_text", "uploaders_file", "uploaders_file_api", "shorteners",
         "sharing", "custom_uploader", "destinations_ui", "main_ui", "packaging"]

TITLES = {
    "mechanisms": "Wayland constraints and platform mappings",
    "hotkeys": "HotkeyType (every job: hotkey, CLI, tray and main menus)",
    "after_capture": "AfterCaptureTasks",
    "after_upload": "AfterUploadTasks",
    "task_settings": "Workflows and task settings",
    "nameparser": "Name parser tokens",
    "shapes": "ShapeType (region capture toolbar and image editor)",
    "editor": "Image editor and shape features",
    "effects": "Image effects (ShareX.ImageEffectsLib)",
    "uploaders_image": "Image uploaders",
    "uploaders_text": "Text uploaders",
    "uploaders_file": "File uploaders (protocols and self-hosted)",
    "uploaders_file_api": "File uploaders (cloud APIs)",
    "destinations_ui": "Destination settings, OAuth and token storage",
    "shorteners": "URL shorteners",
    "sharing": "URL sharing services",
    "custom_uploader": "Custom uploader engine",
    "main_ui": "Main UI and windows",
    "packaging": "Packaging and integration",
}

HEADER = "| ShareX feature | ShareL module | Linux mechanism | Status | Test that proves it |\n|---|---|---|---|---|\n"
ROW = re.compile(r"^\|(.+)\|\s*$")


def rows(text: str) -> list[list[str]]:
    out = []
    for line in text.splitlines():
        m = ROW.match(line.strip())
        if m and not set(line.strip()) <= set("|-: "):
            cells = [c.strip() for c in m.group(1).split("|")]
            if cells and cells[0] != "ShareX feature":
                out.append(cells)
    return out


def status_kind(s: str) -> str:
    s = s.lower()
    if s.startswith("done"):
        return "done"
    if s.startswith("excluded"):
        return "excluded"
    return "open"


def build() -> dict[str, int]:
    parts = ["# ShareL feature map\n",
             "Every ShareX feature in the parity target, the module that implements it, the Linux mechanism "
             "used, its status, and the test that proves it. Generated by `scripts/featuremap.py build` from "
             "`docs/featuremap/*.md`; edit those fragments, not this file.\n"]
    counts = {"done": 0, "excluded": 0, "open": 0}
    names = [n for n in ORDER if (FRAG / f"{n}.md").exists()]
    names += sorted(p.stem for p in FRAG.glob("*.md") if p.stem not in ORDER)
    body = []
    for name in names:
        rs = rows((FRAG / f"{name}.md").read_text())
        for r in rs:
            counts[status_kind(r[3] if len(r) > 3 else "")] += 1
        body.append(f"\n## {TITLES.get(name, name)}\n\n" + HEADER +
                    "".join("| " + " | ".join(r) + " |\n" for r in rs))
    total = sum(counts.values())
    parts.append(f"\n**{total} rows: {counts['done']} done, {counts['excluded']} excluded (defunct service, "
                 f"with evidence), {counts['open']} open.**\n")
    OUT.write_text("".join(parts + body))
    return counts


def main(argv: list[str]) -> int:
    cmd = argv[1] if len(argv) > 1 else "build"
    counts = build()
    print(counts)
    if cmd == "check":
        for p in sorted(FRAG.glob("*.md")):
            for r in rows(p.read_text()):
                if status_kind(r[3] if len(r) > 3 else "") == "open":
                    print(f"open: {p.stem}: {r[0]}")
        return 1 if counts["open"] else 0
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
