# ---- an independent implementation of the PrivateBin v2 decryption steps ------------------------

def b58decode(text: str) -> bytes:
    n = 0
    for ch in text:
        n = n * 58 + ALPHABET.index(ch)
    raw = n.to_bytes((n.bit_length() + 7) // 8, "big") if n else b""
    pad = 0
    for ch in text:
        if ch != "1":
            break
        pad += 1
    return b"\x00" * pad + raw


def decrypt(key_b58: str, password: str, ct_b64: str, adata: list) -> dict:
    spec = adata[0]
    iv, salt = base64.b64decode(spec[0]), base64.b64decode(spec[1])
    iterations, key_bits, tag_bits, algo, mode, compression = spec[2:8]
    assert (algo, mode) == ("aes", "gcm")
    material = b58decode(key_b58) + password.encode("latin-1")
    key = hashlib.pbkdf2_hmac("sha256", material, salt, iterations, dklen=key_bits // 8)
    blob = base64.b64decode(ct_b64)
    tag_len = tag_bits // 8
    decryptor = Cipher(algorithms.AES(key), modes.GCM(iv, blob[-tag_len:], min_tag_length=tag_len)).decryptor()
    decryptor.authenticate_additional_data(json.dumps(adata, separators=(",", ":")).encode())
    plain = decryptor.update(blob[:-tag_len]) + decryptor.finalize()
    if compression == "zlib":
        d = zlib.decompressobj(-15)
        plain = d.decompress(plain) + d.flush()
    return json.loads(plain.decode("utf-8"))


@pytest.mark.parametrize("vec", JS_VECTORS)
def test_independent_decryptor_opens_privatebin_js_pastes(vec):
    assert decrypt(vec["key"], vec["password"], vec["ct"], vec["adata"]) == {"paste": vec["message"]}


@pytest.mark.parametrize("password", ["", "hunter2", "pässwörd"])
def test_client_encryption_decrypts_independently(password):
    text = "ShareL → PrivateBin\n\ttabs \"quotes\" ✓ " + "x" * 2000
    fields, key = pb.encrypt_paste(text, formatter="markdown", open_discussion=True, password=password)
    adata = fields["adata"]
    spec = adata[0]
    assert len(key) == 32
    assert len(base64.b64decode(spec[0])) == 16 and len(base64.b64decode(spec[1])) == 8
    assert spec[2:] == [100000, 256, 128, "aes", "gcm", "zlib"]
    assert adata[1:] == ["markdown", 1, 0]
    assert decrypt(pb.base58_encode(key), password, fields["ct"], adata) == {"paste": text}
    # tampering with the authenticated data must fail
    with pytest.raises(Exception):  # noqa: B017  (cryptography's InvalidTag)
        decrypt(pb.base58_encode(key), password, fields["ct"], [spec, "plaintext", 1, 0])
    if password:
        with pytest.raises(Exception):  # noqa: B017
            decrypt(pb.base58_encode(key), "", fields["ct"], adata)


def test_fixed_inputs_are_deterministic_and_compressed_raw():
    key, iv, salt = bytes(range(32)), bytes(16), b"saltsalt"
    a, _ = pb.encrypt_paste("same", key=key, iv=iv, salt=salt)
    b, _ = pb.encrypt_paste("same", key=key, iv=iv, salt=salt)
    assert a == b
    # The plaintext under GCM is raw deflate (no 0x78 zlib header) of {"paste":"same"}
    k = hashlib.pbkdf2_hmac("sha256", key, salt, 100000, 32)
    blob = base64.b64decode(a["ct"])
    d = Cipher(algorithms.AES(k), modes.GCM(iv, blob[-16:])).decryptor()
    d.authenticate_additional_data(json.dumps(a["adata"], separators=(",", ":")).encode())
    raw = d.update(blob[:-16]) + d.finalize()
    assert zlib.decompress(raw, -15) == b'{"paste":"same"}'


def test_base58_keeps_leading_zero_bytes():
    for data in (b"\x00" + bytes(range(1, 32)), b"\x00\x00" + b"\xff" * 30, b"\xff" * 32, b"\x00" * 32):
        enc = pb.base58_encode(data)
        assert b58decode(enc) == data and pb.base58_decode(enc) == data
    assert pb.base58_encode(b"\x00\x00\x01").startswith("11")
    # base58 of "hello world" (Bitcoin alphabet)
    assert pb.base58_encode(b"hello world") == "StV1DL6CwTryKyV"


def test_js_binary_string_matches_charcodeat_truncation():
    assert pb.js_binary_string("abc") == b"abc"
    assert pb.js_binary_string("päss") == b"p\xe4ss"
    assert pb.js_binary_string("€") == b"\xac"  # U+20AC -> low byte, as Uint8Array.from(charCodeAt)


@responses.activate
def test_upload_request_shape_and_urls():
    responses.post("https://bin.example.org/", json={"status": 0, "id": "f468483c313401e8",
                                                     "url": "/?f468483c313401e8", "deletetoken": "dt0123abcd"})
    s = pb.PrivateBinSettings(custom_url="https://bin.example.org", expiration="D1", format="SyntaxHighlighting",
                              burn_after_reading=True, paste_password="pw", username="u", password="p")
    up = pb.PrivateBinUploader(s, UploadContext())
    assert up.validate() == []
    res = up.upload_text("secret text", "a.txt")
    req = responses.calls[0].request
    assert req.method == "POST" and req.url == "https://bin.example.org/"
    assert req.headers["X-Requested-With"] == "JSONHttpRequest"
    assert req.headers["Content-Type"] == "application/json"
    assert req.headers["Authorization"] == "Basic " + base64.b64encode(b"u:p").decode()
    body = json_body(req)
    assert set(body) == {"v", "adata", "ct", "meta"}  # PrivateBin rejects any extra key
    assert body["v"] == 2 and body["meta"] == {"expire": "1day"}
    assert body["adata"][1:] == ["syntaxhighlighting", 0, 1]
    url = urlsplit(res.url)
    assert f"{url.scheme}://{url.netloc}{url.path}" == "https://bin.example.org/" and url.query == "f468483c313401e8"
    assert decrypt(url.fragment, "pw", body["ct"], body["adata"]) == {"paste": "secret text"}
    assert parse_qs(urlsplit(res.deletion_url).query) == {"pasteid": ["f468483c313401e8"],
                                                          "deletetoken": ["dt0123abcd"]}
    assert res.deletion_url.startswith("https://bin.example.org/?")


@responses.activate
def test_upload_errors():
    responses.post("https://privatebin.net/",
                   json={"status": 1, "message": "Please wait 10 seconds between each post."})
    responses.post("https://privatebin.net/", status=401, body="Unauthorized")
    up = pb.PrivateBinUploader(pb.PrivateBinSettings(), UploadContext())
    with pytest.raises(UploaderError, match="Please wait"):
        up.upload_text("x", "a.txt")
    with pytest.raises(UploaderError, match="requires authorization"):
        up.upload_text("x", "a.txt")
    assert "Authorization" not in responses.calls[0].request.headers
    assert pb.PrivateBinUploader(pb.PrivateBinSettings(burn_after_reading=True, open_discussion=True),
                                 UploadContext()).validate()
