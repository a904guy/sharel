"""Directory indexer window (ShareX DirectoryIndexerForm).

Folder path + Browse (opening the tool asks for a folder straight away, like ShareX's Form_Load), Index,
a Settings tab with every ``IndexerSettings`` field (generated by ``forms.Form``; the fields that exist in
the task's tool settings are written back to it), and a Preview tab with the index text. ShareX previews
HTML in a web browser control; ShareL shows the source and has "Open in browser" (a temporary file opened
with the default browser). Upload sends the index through ``app.tasks.upload_data`` and closes, Save as
writes it (UTF-8) and closes, Copy puts it on the clipboard. Indexing runs on a worker with Cancel.
"""
from __future__ import annotations

import os
import tempfile
from pathlib import Path

import gi

gi.require_version("Gtk", "4.0")
gi.require_version("Adw", "1")
from gi.repository import Adw, Gtk

from ...core import clipboard, desktop
from ...tools.indexer import IndexerOutput, IndexerSettings, index_folder
from ..forms import Form
from ..gtkutil import save_file, select_folder
from ._base import ProgressPanel, ToolWindow, button, file_drop_target, labeled, set_text, single, text_view


def settings_from_task(ts) -> IndexerSettings:
    tool = ts.tool_settings
    return IndexerSettings(output=IndexerOutput(tool.indexer_output), max_depth=tool.indexer_max_depth,
                           skip_hidden_folders=tool.indexer_skip_hidden, skip_hidden_files=tool.indexer_skip_hidden,
                           show_sizes=tool.indexer_show_sizes, custom_css=tool.indexer_custom_css)


class IndexerWindow(ToolWindow):
    def __init__(self, app, ctx) -> None:
        super().__init__(app, "Directory indexer", 820, 640)
        self.ctx = ctx
        self.settings = settings_from_task(ctx.task_settings)
        self.result = None
        self.worker = None

        self.folder = Gtk.Entry(hexpand=True, placeholder_text="Folder to index (or drop a folder here)",
                                tooltip_text="Folder path")
        self.folder.connect("changed", lambda *_: self._update_buttons())
        file_drop_target(self.folder, lambda ps: self.set_folder(ps[0], index=True))
        top = labeled("Folder path:", self.folder)
        top.append(button("Browse…", self.browse, "Choose the folder to index"))
        self.index_button = button("Index folder", self.index, "Build the index", css="suggested-action")
        top.append(self.index_button)

        self.tabs = Gtk.Notebook(vexpand=True)
        prefs = Adw.PreferencesPage()
        prefs.add(Form(self.settings, self._settings_changed, parent=self).group("Indexer settings"))
        self.tabs.append_page(prefs, Gtk.Label(label="Settings"))
        self.preview, psw = text_view(editable=False, monospace=True, height=300)
        self.preview.set_tooltip_text("Index preview")
        self.preview_info = Gtk.Label(xalign=0)
        self.preview_info.add_css_class("dim-label")
        pbox = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=6, margin_top=6, margin_bottom=6,
                       margin_start=6, margin_end=6)
        pbox.append(self.preview_info)
        pbox.append(psw)
        self.tabs.append_page(pbox, Gtk.Label(label="Preview"))

        self.upload_button = button("Upload", self.upload, "Upload the index and close", css="suggested-action")
        self.save_button = button("Save as…", self.save_as, "Save the index to a file and close")
        self.copy_button = button("Copy", self.copy, "Copy the index text")
        self.browser_button = button("Open in browser", self.open_in_browser, "Open the HTML index in the browser")
        actions = Gtk.Box(spacing=8)
        actions.append(self.browser_button)
        actions.append(Gtk.Box(hexpand=True))
        actions.append(self.copy_button)
        actions.append(self.save_button)
        actions.append(self.upload_button)
        self.progress = ProgressPanel()

        body = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=10, margin_top=12, margin_bottom=12,
                       margin_start=12, margin_end=12)
        body.append(top)
        body.append(self.tabs)
        body.append(self.progress)
        body.append(actions)
        self.set_body(body)
        self._update_buttons()

    # -- state --

    def _update_buttons(self) -> None:
        busy = self.worker is not None and self.worker.running
        self.index_button.set_sensitive(bool(self.folder.get_text().strip()) and not busy)
        has = self.result is not None and not busy
        for b in (self.upload_button, self.save_button, self.copy_button):
            b.set_sensitive(has)
        self.browser_button.set_sensitive(has and self.result.extension == "html")

    def _settings_changed(self) -> None:
        tool = self.ctx.task_settings.tool_settings
        tool.indexer_output = self.settings.output
        tool.indexer_max_depth = self.settings.max_depth
        tool.indexer_skip_hidden = self.settings.skip_hidden_folders
        tool.indexer_show_sizes = self.settings.show_sizes
        tool.indexer_custom_css = self.settings.custom_css
        self.app.store.save_app()

    # -- actions --

    def browse(self) -> None:
        select_folder(self, "Index folder", lambda p: p and self.set_folder(p, index=True))

    def set_folder(self, path: str, index: bool = False) -> None:
        self.folder.set_text(path)
        if index:
            self.index()

    def index(self) -> None:
        path = self.folder.get_text().strip()
        if not path or not Path(path).is_dir():
            self.error("Folder not found", path)
            return
        if self.worker is not None and self.worker.running:
            return
        settings = IndexerSettings(**vars(self.settings))

        def work(progress, cancel):
            return index_folder(path, settings, cancel, progress)

        self.worker = self.run(work, self._indexed, panel=self.progress, status="Indexing…",
                               on_finally=self._update_buttons)
        self._update_buttons()

    def _indexed(self, res) -> None:
        self.result = res
        set_text(self.preview, res.text)
        root = res.root
        self.preview_info.set_label(f"{res.suggested_name} — {root.total_file_count} files, "
                                    f"{root.total_folder_count} folders")
        self.progress.set_status(f"Indexed {root.total_file_count} files")
        self.tabs.set_current_page(1)

    @property
    def file_name(self) -> str:
        return self.result.suggested_name if self.result else ""

    def upload(self) -> None:
        if self.result is None:
            return
        self.app.tasks.upload_data(self.result.text.encode("utf-8"), self.result.suggested_name,
                                   self.ctx.task_settings)
        self.close()

    def save_as(self) -> None:
        if self.result is None:
            return
        start = str(Path(self.folder.get_text().strip()).parent) or str(Path.home())
        save_file(self, "Save index as", os.path.join(start, self.result.suggested_name), self.write_to,
                  [f"*.{self.result.extension}"])

    def write_to(self, path: str) -> None:
        if not path or self.result is None:
            return
        try:
            Path(path).write_text(self.result.text, encoding="utf-8")
        except OSError as e:
            self.error("Could not save the index", e)
            return
        self.close()

    def copy(self) -> None:
        if self.result is not None:
            clipboard.set_text(self.result.text)
            self.toast("Index copied")

    def open_in_browser(self) -> None:
        if self.result is None:
            return
        d = tempfile.mkdtemp(prefix="sharel-index-")
        p = Path(d) / self.result.suggested_name
        p.write_text(self.result.text, encoding="utf-8")
        desktop.open_file(str(p))


def open(app, ctx) -> IndexerWindow:  # noqa: A001 - the tool contract's name
    created = {"new": False}

    def make():
        created["new"] = True
        return IndexerWindow(app, ctx)
    win = single("indexer", make)
    folders = [f for f in (getattr(ctx, "files", None) or []) if Path(f).is_dir()]
    if folders:
        win.set_folder(folders[0], index=True)
    elif created["new"]:
        win.browse()
    return win
